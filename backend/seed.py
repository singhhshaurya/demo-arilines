def seed_database(force=False):
    """Seeds initial flights, airlines, and policies if not present."""
    try:
        # Seed Airlines
        if force or airlines_col.count_documents({}) == 0:
            if force:
                airlines_col.delete_many({})
            airlines_col.insert_many(AIRLINES_DATA)
            logger.info("Seeded %d airlines", len(AIRLINES_DATA))

        # Seed Policies
        if force or policies_col.count_documents({}) == 0:
            if force:
                policies_col.delete_many({})
            policies_col.insert_many(POLICIES_DATA)
            logger.info("Seeded %d policies", len(POLICIES_DATA))

        # Seed Flights
        if force or flights_col.count_documents({}) == 0:
            if force:
                flights_col.delete_many({})
            now = datetime.now(timezone.utc)
            for f in INITIAL_FLIGHTS:
                f["created_at"] = now
            flights_col.insert_many(INITIAL_FLIGHTS)
            logger.info("Seeded %d domestic flights", len(INITIAL_FLIGHTS))

        return True
    except Exception as e:
        logger.error("Database seeding failed: %s", e)
        return False


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    print("Running database seed...")
    res = seed_database(force=False)
    print(f"Seed completed: {res}. Flight count: {flights_col.count_documents({})}")
